"""Generate the README case-file board (art/readme/case_file.src.svg).

Each weekly release: update CHAPTERS below (status and public title only;
never put story details here), then run:

    python art/readme/case_file.py
    inkscape art/readme/case_file.src.svg --export-type=svg --export-plain-svg \
        --export-text-to-path --export-filename=.github/readme/case-file.svg
"""
from pathlib import Path

# status: "released" | "in_progress" | "sealed"
CHAPTERS = [
    ("PREP 3", "EP 00", "THE CLINIC", "OCT 12", "in_progress"),
    ("WEEK 1", "EP 01", None, "OCT 19", "sealed"),
    ("WEEK 2", "EP 02", None, "OCT 26", "sealed"),
    ("WEEK 3", "EP 03", None, "NOV 02", "sealed"),
    ("WEEK 4", "EP 04", None, "NOV 09", "sealed"),
    ("WEEK 5", "EP 05", None, "NOV 16", "sealed"),
    ("WEEK 6", "EP 06", None, "NOV 23", "sealed"),
    ("WEEK 7", "EP 07", None, "NOV 30", "sealed"),
    ("WEEK 8", "EP 08", None, "DEC 07", "sealed"),
    ("WEEK 9", "EP 09", None, "DEC 14", "sealed"),
    ("WEEK 10", "EP 10", None, "DEC 21", "sealed"),
    ("WEEK 11", "EP 11", None, "DEC 28", "sealed"),
    ("WEEK 12", "EP 12", None, "JAN 04", "sealed"),
]

W, H = 1280, 340
CARD_W, GAP, X0 = 88, 8, 20
CARD_Y, CARD_H = 104, 170
FONT = 'font-family="Bahnschrift"'
STAMP = {
    "released": ("RELEASED", "#2E8A8A"),
    "in_progress": ("IN PROGRESS", "#B9773C"),
    "sealed": ("SEALED", "#55636C"),
}


def card(i, tab, ep, title, date, status):
    x = X0 + i * (CARD_W + GAP)
    cx = x + CARD_W / 2
    open_file = status != "sealed"
    paper = "#E6DCC3" if open_file else "#26333C"
    ink = "#1B2832" if open_file else "#7D8B93"
    out = [f'<g id="card-{i:02d}">']
    # folder tab + body
    out.append(f'<path d="M {x},{CARD_Y} L {x},{CARD_Y-14} Q {x},{CARD_Y-18} {x+4},{CARD_Y-18} '
               f'L {x+52},{CARD_Y-18} Q {x+56},{CARD_Y-18} {x+58},{CARD_Y-14} L {x+62},{CARD_Y} Z" '
               f'fill="{paper}" stroke="#0B141B" stroke-width="1.5"/>')
    out.append(f'<text x="{x+6}" y="{CARD_Y-5}" {FONT} font-weight="700" font-size="9" '
               f'letter-spacing="1" fill="{ink}">{tab}</text>')
    out.append(f'<rect x="{x}" y="{CARD_Y}" width="{CARD_W}" height="{CARD_H}" rx="2" '
               f'fill="{paper}" stroke="#0B141B" stroke-width="1.5"/>')
    out.append(f'<text x="{x+8}" y="{CARD_Y+46}" {FONT} font-weight="700" font-size="22" '
               f'fill="{ink}">{ep}</text>')
    if open_file:
        out.append(f'<text x="{x+8}" y="{CARD_Y+62}" {FONT} font-weight="700" font-size="10.5" '
                   f'letter-spacing="0.6" fill="#1B2832">{title}</text>')
        for k, w in enumerate((70, 58, 66, 44)):
            out.append(f'<rect x="{x+8}" y="{CARD_Y+73+k*8}" width="{w}" height="3" fill="#8A8366" opacity="0.7"/>')
    else:
        out.append(f'<rect x="{x+8}" y="{CARD_Y+54}" width="62" height="10" fill="#0B141B"/>')
        for k, w in enumerate((72, 50, 66, 38)):
            out.append(f'<rect x="{x+8}" y="{CARD_Y+72+k*8}" width="{w}" height="4" fill="#141E25"/>')
    label, colour = STAMP[status]
    size = 9.5 if status == "in_progress" else 11
    out.append(f'<g transform="rotate(-8 {cx} {CARD_Y+124})">'
               f'<rect x="{x+7}" y="{CARD_Y+113}" width="{CARD_W-14}" height="20" fill="none" '
               f'stroke="{colour}" stroke-width="1.8"/>'
               f'<text x="{cx}" y="{CARD_Y+127}" text-anchor="middle" {FONT} font-weight="700" '
               f'font-size="{size}" letter-spacing="1" fill="{colour}">{label}</text></g>')
    if status == "in_progress":
        out.append(f'<circle class="pulse" cx="{x+CARD_W-12}" cy="{CARD_Y+22}" r="4" fill="#C08A54"/>')
    out.append(f'<text x="{x+8}" y="{CARD_Y+CARD_H-9}" {FONT} font-size="9" letter-spacing="1" '
               f'fill="{ink}" opacity="0.8">{date}</text>')
    # pin
    out.append(f'<circle cx="{cx}" cy="{CARD_Y+8}" r="5" fill="#8C7A4E" stroke="#0B141B" stroke-width="1.2"/>')
    out.append(f'<circle cx="{cx-1.4}" cy="{CARD_Y+6.6}" r="1.4" fill="#E6DCC3" opacity="0.8"/>')
    out.append('</g>')
    return "\n".join(out)


def string_path():
    pts = [X0 + i * (CARD_W + GAP) + CARD_W / 2 for i in range(len(CHAPTERS))]
    y = CARD_Y + 8
    d = f"M {pts[0]},{y}"
    for a, b in zip(pts, pts[1:]):
        d += f" Q {(a+b)/2},{y+16} {b},{y}"
    return d


def build():
    released = sum(1 for c in CHAPTERS if c[4] == "released")
    cards = "\n".join(card(i, *c) for i, c in enumerate(CHAPTERS))
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by art/readme/case_file.py. Edit CHAPTERS there, not this file. -->
<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">
  <style>
    @keyframes pulse {{ 0%, 100% {{ opacity: 0.35; }} 50% {{ opacity: 1; }} }}
    .pulse {{ animation: pulse 2.4s ease-in-out infinite; }}
    @media (prefers-reduced-motion: reduce) {{ .pulse {{ animation: none; }} }}
  </style>
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#121E27"/><stop offset="1" stop-color="#0E1820"/>
    </linearGradient>
    <radialGradient id="lamp" cx="0.5" cy="0" r="0.9">
      <stop offset="0" stop-color="#C08A54" stop-opacity="0.16"/><stop offset="1" stop-color="#C08A54" stop-opacity="0"/>
    </radialGradient>
  </defs>
  <rect width="{W}" height="{H}" fill="url(#bg)"/>
  <rect width="{W}" height="{H}" fill="url(#lamp)"/>
  <rect x="0" y="0" width="{W}" height="4" fill="#3E7F7A" opacity="0.8"/>
  <text x="20" y="44" {FONT} font-weight="700" font-size="20" letter-spacing="4" fill="#E6DCC3">CASE FILE · THE MERIDIAN</text>
  <text x="20" y="66" {FONT} font-size="12" letter-spacing="2" fill="#70CFCF">{released} OF {len(CHAPTERS)} FILES RELEASED · A NEW FILE OPENS EACH WEEK</text>
  <g {FONT} font-size="11" letter-spacing="1.5">
    <circle cx="930" cy="40" r="5" fill="#2E8A8A"/><text x="941" y="44" fill="#9FB0B8">RELEASED</text>
    <circle cx="1040" cy="40" r="5" fill="#C08A54"/><text x="1051" y="44" fill="#9FB0B8">IN PROGRESS</text>
    <circle cx="1170" cy="40" r="5" fill="#55636C"/><text x="1181" y="44" fill="#9FB0B8">SEALED</text>
  </g>
  {cards}
  <path d="{string_path()}" fill="none" stroke="#C08A54" stroke-width="1.6" opacity="0.85"/>
  <text x="20" y="{H-18}" {FONT} font-size="11" letter-spacing="1.5" fill="#55636C">SEALED FILES STAY SEALED UNTIL THEY SHIP. NO SPOILERS IN THIS REPOSITORY.</text>
</svg>
'''


if __name__ == "__main__":
    out = Path(__file__).with_name("case_file.src.svg")
    out.write_text(build(), encoding="utf-8")
    print(f"wrote {out}")
